import Darwin
import Foundation

/// EasyTier TOML 配置的生成、解析与基础校验。
enum TOMLCodec {
    struct Imported {
        var name: String
        var secret: String
        var config: NetworkConfig
    }

    // MARK: - Export

    /// `staticIPv4`：运行期覆盖（沿用上次租约/应用侧分配的 IP），写成固定 IP 并关闭 core 内置 DHCP。
    /// 不影响导出：导出时不传该参数，保持用户配置原样。
    static func render(_ profile: NetworkProfile, secret: String, staticIPv4: String? = nil) -> String {
        let config = profile.config
        var lines: [String] = []

        lines.append("# Generated by MacEasyTier")
        lines.append("instance_name = \(quote(config.instanceName))")
        lines.append("hostname = \(quote(config.hostname))")

        if let staticIPv4, !staticIPv4.isEmpty {
            lines.append("dhcp = false")
            lines.append("ipv4 = \(quote(staticIPv4))")
        } else {
            lines.append("dhcp = \(config.dhcp ? "true" : "false")")
            if !config.dhcp, !config.virtualIPv4.isEmpty {
                lines.append("ipv4 = \(quote(config.virtualIPv4))")
            }
        }
        if config.noListener {
            lines.append("listeners = []")
        } else if !config.listeners.isEmpty {
            lines.append("listeners = \(array(config.listeners))")
        }
        if !config.exitNodes.isEmpty {
            lines.append("exit_nodes = \(array(config.exitNodes))")
        }
        if !config.manualRoutes.isEmpty {
            lines.append("routes = \(array(config.manualRoutes))")
        }
        if let port = config.socks5Port {
            lines.append("socks5_proxy = \(quote("socks5://0.0.0.0:\(port)"))")
        }

        lines.append("")
        lines.append("[network_identity]")
        lines.append("network_name = \(quote(config.networkName))")
        lines.append("network_secret = \(quote(secret))")

        var peerURLs = config.peers.filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
        if config.method == .publicServer, !config.publicServer.isEmpty {
            peerURLs.insert(config.publicServer, at: 0)
        }
        for peer in peerURLs {
            lines.append("")
            lines.append("[[peer]]")
            lines.append("uri = \(quote(peer))")
        }

        for network in config.proxyNetworks where !network.cidr.trimmingCharacters(in: .whitespaces).isEmpty {
            lines.append("")
            lines.append("[[proxy_network]]")
            lines.append("cidr = \(quote(network.cidr))")
            if !network.mappedCIDR.trimmingCharacters(in: .whitespaces).isEmpty {
                lines.append("mapped_cidr = \(quote(network.mappedCIDR))")
            }
            if !network.allow.isEmpty {
                lines.append("allow = \(array(network.allow))")
            }
        }

        for rule in config.portForwards {
            lines.append("")
            lines.append("[[port_forward]]")
            lines.append("proto = \(quote(rule.proto))")
            lines.append("bind_addr = \(quote(rule.bindAddress))")
            lines.append("dst_addr = \(quote(rule.destination))")
        }

        lines.append("")
        lines.append("[flags]")
        lines.append("no_tun = \(bool(!config.usesTUN))")
        lines.append("latency_first = \(bool(config.advanced.latencyFirst))")
        lines.append("disable_p2p = \(bool(config.advanced.disableP2P))")
        lines.append("enable_kcp_proxy = \(bool(config.advanced.enableKCPProxy))")
        lines.append("enable_quic_proxy = \(bool(config.advanced.enableQUICProxy))")
        lines.append("enable_exit_node = \(bool(config.enableExitNode))")
        lines.append("private_mode = \(bool(config.advanced.privateMode))")
        lines.append("accept_dns = \(bool(config.advanced.acceptDNS))")
        lines.append("data_compress_algo = \(config.advanced.compression == "zstd" ? 2 : 1)")
        if config.advanced.mtu > 0 {
            lines.append("mtu = \(config.advanced.mtu)")
        }
        if !config.advanced.encryptionAlgorithm.isEmpty {
            lines.append("encryption_algorithm = \(quote(config.advanced.encryptionAlgorithm))")
        }
        if config.advanced.relayNetworkWhitelist != "*" {
            lines.append("relay_network_whitelist = \(quote(config.advanced.relayNetworkWhitelist))")
        }

        return lines.joined(separator: "\n") + "\n"
    }

    // MARK: - Import

    static func parse(_ text: String) throws -> Imported {
        let document = try TOMLDocument.parse(text)
        let root = document.root
        let identity = document.tables["network_identity"] ?? [:]
        let flags = document.tables["flags"] ?? [:]

        let instanceName = root.string("instance_name") ?? root.string("hostname") ?? "Imported Network"
        let hostname = root.string("hostname") ?? instanceName
        let networkName = identity.string("network_name") ?? ""
        let secret = identity.string("network_secret") ?? ""
        let dhcp = root.bool("dhcp") ?? (root.string("ipv4") == nil)
        let virtualIPv4 = root.string("ipv4") ?? ""

        let peerURLs = (document.arrayTables["peer"] ?? []).compactMap { $0.string("uri") }
        let proxyNetworks = (document.arrayTables["proxy_network"] ?? []).map {
            ProxyNetwork(
                cidr: $0.string("cidr") ?? "",
                mappedCIDR: $0.string("mapped_cidr") ?? "",
                allow: $0.stringArray("allow") ?? []
            )
        }
        let portForwards = (document.arrayTables["port_forward"] ?? []).map {
            PortForwardRule(
                proto: $0.string("proto") ?? "tcp",
                bindAddress: $0.string("bind_addr") ?? "",
                destination: $0.string("dst_addr") ?? ""
            )
        }

        var socks5Port: Int?
        if let value = root.string("socks5_proxy"),
           let components = URLComponents(string: value),
           let port = components.port {
            socks5Port = port
        }

        var advanced = AdvancedConfig()
        advanced.latencyFirst = flags.bool("latency_first") ?? false
        advanced.disableP2P = flags.bool("disable_p2p") ?? false
        advanced.enableKCPProxy = flags.bool("enable_kcp_proxy") ?? false
        advanced.enableQUICProxy = flags.bool("enable_quic_proxy") ?? false
        advanced.compression = (flags.int("data_compress_algo") == 2) ? "zstd" : "none"
        advanced.encryptionAlgorithm = flags.string("encryption_algorithm") ?? "aes-gcm"
        advanced.mtu = flags.int("mtu") ?? 0
        advanced.relayNetworkWhitelist = flags.string("relay_network_whitelist") ?? "*"
        advanced.privateMode = flags.bool("private_mode") ?? false
        advanced.acceptDNS = flags.bool("accept_dns") ?? false

        let listenerValues = root.stringArray("listeners")
        let config = NetworkConfig(
            instanceName: instanceName,
            networkName: networkName,
            hostname: hostname,
            method: peerURLs.isEmpty ? .standalone : .manual,
            peers: peerURLs,
            listeners: listenerValues ?? NetworkConfig.defaultListeners,
            noListener: listenerValues?.isEmpty ?? false,
            tunEnabled: !(flags.bool("no_tun") ?? false),
            dhcp: dhcp,
            virtualIPv4: virtualIPv4,
            proxyNetworks: proxyNetworks,
            manualRoutes: root.stringArray("routes") ?? [],
            exitNodes: root.stringArray("exit_nodes") ?? [],
            enableExitNode: flags.bool("enable_exit_node") ?? false,
            socks5Port: socks5Port,
            portForwards: portForwards,
            advanced: advanced
        )

        return Imported(name: instanceName, secret: secret, config: config)
    }

    // MARK: - Validation

    static func validate(_ config: NetworkConfig) -> [String] {
        var errors: [String] = []

        if config.networkName.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            errors.append("网络名称不能为空。")
        }
        if config.instanceName.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            errors.append("实例名称不能为空。")
        }
        if !config.dhcp {
            if config.virtualIPv4.isEmpty {
                errors.append("关闭 DHCP 时必须填写虚拟 IPv4。")
            } else if !isIPv4CIDR(config.virtualIPv4) {
                errors.append("虚拟 IPv4 格式应类似 10.144.144.1/24。")
            }
        }
        if config.method == .publicServer, config.publicServer.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            errors.append("必须填写公共节点地址。")
        }
        if config.method == .manual, effectivePeers(config).isEmpty {
            errors.append("客户端模式至少需要一个对等节点地址才能加入网络。")
        }
        if config.noListener && config.method == .standalone && config.peers.isEmpty {
            errors.append("服务端模式至少需要一个监听地址。")
        }

        for peer in effectivePeers(config) {
            if !isPeerURL(peer) {
                errors.append("对等节点地址无效：\(peer)")
            }
        }
        for listener in config.listeners where !config.noListener {
            if !isListenerURL(listener) {
                errors.append("监听地址无效：\(listener)。应使用类似 tcp://0.0.0.0:11010 的地址。")
            } else if let host = listenerBindHost(listener), !isLocalBindHost(host) {
                errors.append("监听地址 \(listener) 使用了 \(host)，但该地址不属于本机。请改用 0.0.0.0:<端口>（所有网卡）或本机网卡地址。")
            }
        }
        for network in config.proxyNetworks where !network.cidr.isEmpty {
            if !isIPv4CIDR(network.cidr) {
                errors.append("代理网段无效：\(network.cidr)")
            }
            if !network.mappedCIDR.isEmpty && !isIPv4CIDR(network.mappedCIDR) {
                errors.append("映射网段无效：\(network.mappedCIDR)")
            }
        }
        for route in config.manualRoutes where !isIPv4CIDR(route) {
            errors.append("手动路由无效：\(route)")
        }
        for node in config.exitNodes where !isIPv4(node) {
            errors.append("出口节点无效：\(node)")
        }
        if let port = config.socks5Port, !(1 ... 65535).contains(port) {
            errors.append("SOCKS5 端口必须在 1–65535 之间。")
        }
        for rule in config.portForwards {
            if rule.proto != "tcp" && rule.proto != "udp" {
                errors.append("端口转发协议必须是 tcp 或 udp。")
            }
            if !isHostPort(rule.bindAddress) {
                errors.append("端口转发监听地址无效：\(rule.bindAddress)")
            }
            if !isHostPort(rule.destination) {
                errors.append("端口转发目标地址无效：\(rule.destination)")
            }
        }

        return errors
    }

    static func effectivePeers(_ config: NetworkConfig) -> [String] {
        var peers = config.peers
        if config.method == .publicServer, !config.publicServer.isEmpty {
            peers.insert(config.publicServer, at: 0)
        }
        return peers.filter { !$0.trimmingCharacters(in: .whitespaces).isEmpty }
    }

    // MARK: - Helpers

    private static func quote(_ value: String) -> String {
        let escaped = value
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
            .replacingOccurrences(of: "\n", with: "\\n")
            .replacingOccurrences(of: "\r", with: "\\r")
            .replacingOccurrences(of: "\t", with: "\\t")
        return "\"\(escaped)\""
    }

    private static func array(_ values: [String]) -> String {
        "[" + values.map(quote).joined(separator: ", ") + "]"
    }

    private static func bool(_ value: Bool) -> String {
        value ? "true" : "false"
    }

    private static func isIPv4(_ value: String) -> Bool {
        let parts = value.split(separator: ".")
        guard parts.count == 4 else { return false }
        return parts.allSatisfy { part in
            guard let number = Int(part), (0 ... 255).contains(number) else { return false }
            return String(number) == String(part)
        }
    }

    private static func isIPv4CIDR(_ value: String) -> Bool {
        let parts = value.split(separator: "/", omittingEmptySubsequences: false)
        guard parts.count == 2, isIPv4(String(parts[0])), let prefix = Int(parts[1]), (0 ... 32).contains(prefix) else {
            return false
        }
        return true
    }

    private static func isHostPort(_ value: String) -> Bool {
        guard let components = URLComponents(string: "tcp://\(value)"),
              let host = components.host, !host.isEmpty,
              let port = components.port, (1 ... 65535).contains(port) else { return false }
        return true
    }

    private static func isPeerURL(_ value: String) -> Bool {
        guard let components = URLComponents(string: value),
              let scheme = components.scheme?.lowercased(),
              ["tcp", "udp", "ws", "wss", "quic", "wg", "ring", "faketcp", "txt", "srv", "http", "https"].contains(scheme),
              components.host != nil || scheme == "ring" else { return false }
        return true
    }

    private static func isListenerURL(_ value: String) -> Bool {
        guard let components = URLComponents(string: value),
              let scheme = components.scheme?.lowercased(),
              ["tcp", "udp", "ws", "wss", "quic", "wg", "ring", "faketcp"].contains(scheme),
              components.host != nil else { return false }
        return true
    }

    private static func listenerBindHost(_ value: String) -> String? {
        guard let components = URLComponents(string: value),
              components.scheme?.lowercased() != "ring" else { return nil }
        return components.host?.trimmingCharacters(in: CharacterSet(charactersIn: "[]"))
    }

    private static func isLocalBindHost(_ host: String) -> Bool {
        if ["0.0.0.0", "::", "127.0.0.1", "::1", "localhost"].contains(host) {
            return true
        }
        // 只对 IP 字面量做严格校验；主机名交给系统解析，避免误判 mDNS 名称。
        if isIPv4(host) || host.contains(":") {
            return LocalAddresses.all.contains(host)
        }
        return true
    }
}

private enum LocalAddresses {
    static var all: Set<String> {
        var result = Set<String>()
        var head: UnsafeMutablePointer<ifaddrs>?
        guard getifaddrs(&head) == 0, let first = head else { return result }
        defer { freeifaddrs(head) }

        var pointer: UnsafeMutablePointer<ifaddrs>? = first
        while let current = pointer {
            pointer = current.pointee.ifa_next
            guard let address = current.pointee.ifa_addr else { continue }
            var host = [CChar](repeating: 0, count: Int(NI_MAXHOST))
            let length = socklen_t(address.pointee.sa_len)
            if getnameinfo(address, length, &host, socklen_t(host.count), nil, 0, NI_NUMERICHOST) == 0 {
                let bytes = host.prefix { $0 != 0 }.map { UInt8(bitPattern: $0) }
                result.insert(String(decoding: bytes, as: UTF8.self))
            }
        }
        return result
    }
}

// MARK: - Minimal TOML document

private enum TOMLValue {
    case string(String)
    case bool(Bool)
    case int(Int)
    case double(Double)
    case array([TOMLValue])

    var stringValue: String? {
        if case let .string(value) = self { return value }
        return nil
    }

    var boolValue: Bool? {
        if case let .bool(value) = self { return value }
        return nil
    }

    var intValue: Int? {
        if case let .int(value) = self { return value }
        return nil
    }

    var arrayValue: [TOMLValue]? {
        if case let .array(value) = self { return value }
        return nil
    }
}

private struct TOMLDocument {
    var root: [String: TOMLValue] = [:]
    var tables: [String: [String: TOMLValue]] = [:]
    var arrayTables: [String: [[String: TOMLValue]]] = [:]

    static func parse(_ text: String) throws -> TOMLDocument {
        var document = TOMLDocument()
        var currentSection: String?
        var currentArrayTable: String?
        var buffer = ""
        var bracketDepth = 0

        func flush(_ line: String) throws {
            let trimmed = line.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return }

            if trimmed.hasPrefix("[[") && trimmed.hasSuffix("]]") {
                let name = String(trimmed.dropFirst(2).dropLast(2)).trimmingCharacters(in: .whitespaces)
                currentSection = nil
                currentArrayTable = name
                document.arrayTables[name, default: []].append([:])
                return
            }
            if trimmed.hasPrefix("[") && trimmed.hasSuffix("]") {
                currentSection = String(trimmed.dropFirst().dropLast()).trimmingCharacters(in: .whitespaces)
                currentArrayTable = nil
                return
            }

            guard let equals = firstUnquoted(trimmed, character: "=") else { return }
            let key = String(trimmed[..<equals]).trimmingCharacters(in: .whitespaces)
            let valueText = String(trimmed[trimmed.index(after: equals)...]).trimmingCharacters(in: .whitespaces)
            let value = try parseValue(valueText)

            if let name = currentArrayTable {
                var tables = document.arrayTables[name] ?? []
                guard !tables.isEmpty else { return }
                tables[tables.count - 1][key] = value
                document.arrayTables[name] = tables
            } else if let name = currentSection {
                document.tables[name, default: [:]][key] = value
            } else {
                document.root[key] = value
            }
        }

        for rawLine in text.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = stripComment(String(rawLine))
            if buffer.isEmpty {
                buffer = line
            } else {
                buffer += " " + line
            }
            bracketDepth = bracketBalance(buffer)
            if bracketDepth <= 0 {
                try flush(buffer)
                buffer = ""
                bracketDepth = 0
            }
        }
        if !buffer.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            try flush(buffer)
        }

        return document
    }

    private static func stripComment(_ line: String) -> String {
        var inString = false
        var escaped = false
        for index in line.indices {
            let character = line[index]
            if escaped {
                escaped = false
                continue
            }
            if character == "\\", inString {
                escaped = true
                continue
            }
            if character == "\"" {
                inString.toggle()
            } else if character == "#", !inString {
                return String(line[..<index])
            }
        }
        return line
    }

    private static func bracketBalance(_ line: String) -> Int {
        var depth = 0
        var inString = false
        var escaped = false
        for character in line {
            if escaped {
                escaped = false
                continue
            }
            if character == "\\", inString {
                escaped = true
                continue
            }
            if character == "\"" {
                inString.toggle()
            } else if character == "[", !inString {
                depth += 1
            } else if character == "]", !inString {
                depth -= 1
            }
        }
        return depth
    }

    private static func firstUnquoted(_ line: String, character target: Character) -> String.Index? {
        var inString = false
        var escaped = false
        for index in line.indices {
            let character = line[index]
            if escaped {
                escaped = false
                continue
            }
            if character == "\\", inString {
                escaped = true
                continue
            }
            if character == "\"" {
                inString.toggle()
            } else if character == target, !inString {
                return index
            }
        }
        return nil
    }

    private static func parseValue(_ text: String) throws -> TOMLValue {
        let trimmed = text.trimmingCharacters(in: .whitespaces)
        if trimmed.hasPrefix("\"") {
            return .string(try parseString(trimmed))
        }
        if trimmed == "true" { return .bool(true) }
        if trimmed == "false" { return .bool(false) }
        if trimmed.hasPrefix("[") {
            return .array(try parseArray(trimmed))
        }
        if let value = Int(trimmed) { return .int(value) }
        if let value = Double(trimmed) { return .double(value) }
        // 容错：未加引号的裸值按字符串处理。
        return .string(trimmed)
    }

    private static func parseString(_ text: String) throws -> String {
        var result = ""
        var escaped = false
        var closed = false
        for character in text.dropFirst() {
            if escaped {
                switch character {
                case "n": result.append("\n")
                case "r": result.append("\r")
                case "t": result.append("\t")
                case "\\": result.append("\\")
                case "\"": result.append("\"")
                default: result.append(character)
                }
                escaped = false
                continue
            }
            if character == "\\" {
                escaped = true
            } else if character == "\"" {
                closed = true
                break
            } else {
                result.append(character)
            }
        }
        guard closed else { throw TOMLParseError.invalidValue(text) }
        return result
    }

    private static func parseArray(_ text: String) throws -> [TOMLValue] {
        guard text.hasPrefix("["), text.hasSuffix("]") else {
            throw TOMLParseError.invalidValue(text)
        }
        let body = String(text.dropFirst().dropLast())
        var values: [TOMLValue] = []
        var current = ""
        var inString = false
        var escaped = false
        var depth = 0

        for character in body {
            if escaped {
                current.append(character)
                escaped = false
                continue
            }
            if character == "\\", inString {
                current.append(character)
                escaped = true
                continue
            }
            if character == "\"" {
                inString.toggle()
                current.append(character)
                continue
            }
            if character == "[", !inString {
                depth += 1
            } else if character == "]", !inString {
                depth -= 1
            }
            if character == ",", !inString, depth == 0 {
                let item = current.trimmingCharacters(in: .whitespacesAndNewlines)
                if !item.isEmpty { values.append(try parseValue(item)) }
                current = ""
            } else {
                current.append(character)
            }
        }
        let item = current.trimmingCharacters(in: .whitespacesAndNewlines)
        if !item.isEmpty { values.append(try parseValue(item)) }
        return values
    }

    enum TOMLParseError: LocalizedError {
        case invalidValue(String)

        var errorDescription: String? {
            switch self {
            case let .invalidValue(value): "无效的 TOML 值：\(value)"
            }
        }
    }
}

private extension Dictionary where Key == String, Value == TOMLValue {
    func string(_ key: String) -> String? { self[key]?.stringValue }
    func bool(_ key: String) -> Bool? { self[key]?.boolValue }
    func int(_ key: String) -> Int? { self[key]?.intValue }

    func stringArray(_ key: String) -> [String]? {
        self[key]?.arrayValue?.compactMap(\.stringValue)
    }
}
